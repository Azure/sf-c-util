#include "sf_c_util/sf_service_config.h"

#include "umock_c/umock_c_prod.h"

/*DEFINE_SF_SERVICE_CONFIG(name, ...) generates its code in the consumer, so sf_c_util cannot ship its real. The consumer builds it:

real_<consumer>_renames.h:
    #define name real_name
    #define real_name_CONFIGURATION_TAG name_CONFIGURATION_TAG

real_<consumer>.c (the renames come before any other include):
    #include "real_sf_service_config_dependencies_renames.h"
    #include "real_<consumer>_renames.h"
    #include "../../src/<consumer>.c"

DECLARE/DEFINE_SF_SERVICE_CONFIG paste every identifier they generate from name, so the first define renames the THANDLE type, create, getters,
refresh and statics to real_name. The second define keeps the struct tag of the plain type, so THANDLE(SF_SERVICE_CONFIG(real_name)) is the same
type as THANDLE(SF_SERVICE_CONFIG(name)). The real of code that calls SF_SERVICE_CONFIG_CREATE(name) or SF_SERVICE_CONFIG_GETTER(name, ...) includes
real_<consumer>_renames.h too, tests/real_sf_service_config_ut/real_sample_config_consumer.c is an example.

A unit test declares the real functions with DECLARE_REAL_SF_SERVICE_CONFIG(name, ...) and hooks the mocks generated by DECLARE_SF_SERVICE_CONFIG
with REGISTER_SF_SERVICE_CONFIG_GLOBAL_MOCK_HOOK(name, ...).*/

#define DECLARE_REAL_SF_SERVICE_CONFIG(name, ...) \
    DECLARE_REAL_SF_SERVICE_CONFIG_IMPL(name, MU_C2(real_, name), __VA_ARGS__)

#define DECLARE_REAL_SF_SERVICE_CONFIG_IMPL(name, real_name, ...) \
    typedef SF_SERVICE_CONFIG(name) SF_SERVICE_CONFIG(real_name); \
    THANDLE_TYPE_DECLARE(SF_SERVICE_CONFIG(real_name)); \
    MOCKABLE_FUNCTION(, THANDLE(SF_SERVICE_CONFIG(real_name)), SF_SERVICE_CONFIG_CREATE(real_name), IFabricCodePackageActivationContext*, activation_context); \
    DECLARE_SF_SERVICE_CONFIG_GETTERS(real_name, __VA_ARGS__) \
    DECLARE_SF_SERVICE_CONFIG_REFRESH(real_name)

#define REGISTER_SF_SERVICE_CONFIG_GETTER_GLOBAL_MOCK_HOOK(name, type, param) \
    REGISTER_GLOBAL_MOCK_HOOK(SF_SERVICE_CONFIG_GETTER(name, param), SF_SERVICE_CONFIG_GETTER(MU_C2(real_, name), param));

#define REGISTER_SF_SERVICE_CONFIG_GLOBAL_MOCK_HOOK(name, ...) \
    REGISTER_GLOBAL_MOCK_HOOK(SF_SERVICE_CONFIG_CREATE(name), SF_SERVICE_CONFIG_CREATE(MU_C2(real_, name))); \
    SF_SERVICE_CONFIG_EXPANDED_MU_FOR_EACH_2_KEEP_1(REGISTER_SF_SERVICE_CONFIG_GETTER_GLOBAL_MOCK_HOOK, name, SF_SERVICE_CONFIG_EXPAND_PARAMS(__VA_ARGS__)) \
    REGISTER_GLOBAL_MOCK_HOOK(SF_SERVICE_CONFIG_REFRESH(name), SF_SERVICE_CONFIG_REFRESH(MU_C2(real_, name))); \
    REGISTER_GLOBAL_MOCK_HOOK(THANDLE_ASSIGN(SF_SERVICE_CONFIG(name)), THANDLE_ASSIGN(SF_SERVICE_CONFIG(MU_C2(real_, name)))); \
    REGISTER_GLOBAL_MOCK_HOOK(THANDLE_INITIALIZE(SF_SERVICE_CONFIG(name)), THANDLE_INITIALIZE(SF_SERVICE_CONFIG(MU_C2(real_, name)))); \
    REGISTER_GLOBAL_MOCK_HOOK(THANDLE_MOVE(SF_SERVICE_CONFIG(name)), THANDLE_MOVE(SF_SERVICE_CONFIG(MU_C2(real_, name)))); \
    REGISTER_GLOBAL_MOCK_HOOK(THANDLE_INITIALIZE_MOVE(SF_SERVICE_CONFIG(name)), THANDLE_INITIALIZE_MOVE(SF_SERVICE_CONFIG(MU_C2(real_, name))));

#endif //REAL_SF_SERVICE_CONFIG_H
